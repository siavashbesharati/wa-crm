/**
 * Sync global extension version from config/extension.json into:
 * - WAchromeExtension/manifest.json
 * - platform/web/public/downloads/extension-meta.json
 * - platform/web/lib/extension.ts (fallback constant)
 * - platform/api/app/extension_version.json (API mirror)
 *
 * Usage (repo root):
 *   node scripts/sync-extension-version.mjs
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const configPath = join(root, "config", "extension.json");

if (!existsSync(configPath)) {
  console.error("Missing", configPath);
  process.exit(1);
}

const cfg = JSON.parse(readFileSync(configPath, "utf8"));
const version = String(cfg.version || "").trim();
const downloadFile = String(cfg.download_file || "iranexpedia-extension.zip");
const downloadPath = String(cfg.download_path || `/downloads/${downloadFile}`);

if (!/^\d+\.\d+\.\d+(\.\d+)?$/.test(version)) {
  console.error("Invalid version in config/extension.json:", version);
  process.exit(1);
}

const meta = {
  version,
  file: downloadFile,
  download_path: downloadPath,
  synced_at: new Date().toISOString()
};

// 1) manifest.json
const manifestPath = join(root, "WAchromeExtension", "manifest.json");
const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
manifest.version = version;
writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + "\n");
console.log("Updated", manifestPath, `→ ${version}`);

// 2) public meta for Next static download UI
const downloadsDir = join(root, "platform", "web", "public", "downloads");
mkdirSync(downloadsDir, { recursive: true });
const metaPath = join(downloadsDir, "extension-meta.json");
writeFileSync(metaPath, JSON.stringify(meta, null, 2) + "\n");
console.log("Updated", metaPath);

// 3) API mirror (works even if repo-root config is unavailable in deploy)
const apiMirrorDir = join(root, "platform", "api", "app");
const apiMirrorPath = join(apiMirrorDir, "extension_version.json");
writeFileSync(apiMirrorPath, JSON.stringify(meta, null, 2) + "\n");
console.log("Updated", apiMirrorPath);

// 4) web TS fallback constant
const webLibPath = join(root, "platform", "web", "lib", "extension.ts");
const webLib = `/** Chrome extension download metadata for the business panel.
 * FALLBACK only — prefer GET /api/extension/latest or /downloads/extension-meta.json.
 * Regenerated by: npm run sync:ext-version
 */
export const EXTENSION_DOWNLOAD_URL = ${JSON.stringify(downloadPath)};
export const EXTENSION_DOWNLOAD_NAME = ${JSON.stringify(downloadFile)};

/** Fallback if API / meta are unreachable. Synced from config/extension.json */
export const EXTENSION_VERSION_FALLBACK = ${JSON.stringify(version)};

export type ExtensionMeta = {
  version: string;
  file: string;
  download_path?: string;
};
`;
writeFileSync(webLibPath, webLib);
console.log("Updated", webLibPath);

console.log(`\nExtension version synced: v${version}`);
console.log("Source of truth: config/extension.json");
